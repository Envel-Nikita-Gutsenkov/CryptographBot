use serde::{Deserialize, Serialize};

/// A single purchase to add to the portfolio.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewPurchase {
    pub symbol: String,
    pub amount: f64,
    /// Cost in USD (total, not per unit).
    pub cost_usd: f64,
    /// Optional wallet name to associate the holding with.
    pub wallet_name: Option<String>,
    pub source: Option<String>,
    pub notes: Option<String>,
    pub date: Option<String>,
}

/// Adjust an existing holding's amount directly (like /adjust).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HoldingAdjust {
    pub symbol: String,
    /// Optional wallet name; if None, applies to the first matching holding.
    pub wallet_name: Option<String>,
    pub new_amount: f64,
}

/// Modify fields of an existing purchase record.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PurchaseModify {
    pub purchase_id: u64,
    pub new_amount: Option<f64>,
    pub new_cost_usd: Option<f64>,
    pub new_source: Option<String>,
    pub new_notes: Option<String>,
    pub new_date: Option<String>,
}

/// The full patch generated by the AI. Applied to the portfolio only after user approval.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct PortfolioPatch {
    pub add_purchases: Vec<NewPurchase>,
    pub remove_purchase_ids: Vec<u64>,
    pub adjust_holdings: Vec<HoldingAdjust>,
    pub modify_purchases: Vec<PurchaseModify>,
    /// Human-readable summary the AI generated to explain what it is doing and why.
    pub description: String,
}

impl PortfolioPatch {
    pub fn is_empty(&self) -> bool {
        self.add_purchases.is_empty()
            && self.remove_purchase_ids.is_empty()
            && self.adjust_holdings.is_empty()
            && self.modify_purchases.is_empty()
    }

    /// Total number of changes in this patch.
    pub fn change_count(&self) -> usize {
        self.add_purchases.len()
            + self.remove_purchase_ids.len()
            + self.adjust_holdings.len()
            + self.modify_purchases.len()
    }
}

/// A pending patch waiting for user approval.
#[derive(Debug, Clone)]
pub struct PendingPatch {
    pub user_id: u64,
    pub patch: PortfolioPatch,
    pub expires_at: std::time::Instant,
}

impl PendingPatch {
    pub fn new(user_id: u64, patch: PortfolioPatch) -> Self {
        Self {
            user_id,
            patch,
            expires_at: std::time::Instant::now() + std::time::Duration::from_secs(600),
        }
    }

    pub fn is_expired(&self) -> bool {
        std::time::Instant::now() > self.expires_at
    }
}

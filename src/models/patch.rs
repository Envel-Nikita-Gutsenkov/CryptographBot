use serde::{Deserialize, Serialize};

/// A single purchase to add to the portfolio.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewPurchase {
    pub symbol: String,
    pub amount: f64,
    /// Cost in USD (total, not per unit).
    pub cost_usd: f64,
    /// Optional wallet name to associate the holding with.
    pub wallet_name: Option<String>,
    pub source: Option<String>,
    pub notes: Option<String>,
    pub date: Option<String>,
}

/// Adjust an existing holding's amount directly (like /adjust).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HoldingAdjust {
    pub symbol: String,
    /// Optional wallet name; if None, applies to the first matching holding.
    pub wallet_name: Option<String>,
    pub new_amount: f64,
}

/// Modify fields of an existing purchase record.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PurchaseModify {
    pub purchase_id: u64,
    pub new_amount: Option<f64>,
    pub new_cost_usd: Option<f64>,
    pub new_source: Option<String>,
    pub new_notes: Option<String>,
    pub new_date: Option<String>,
}

/// The full patch generated by the AI. Applied to the portfolio only after user approval.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct PortfolioPatch {
    pub add_purchases: Vec<NewPurchase>,
    pub remove_purchase_ids: Vec<u64>,
    pub adjust_holdings: Vec<HoldingAdjust>,
    pub modify_purchases: Vec<PurchaseModify>,
    /// Human-readable summary the AI generated to explain what it is doing and why.
    pub description: String,
}

impl PortfolioPatch {
    pub fn is_empty(&self) -> bool {
        self.add_purchases.is_empty()
            && self.remove_purchase_ids.is_empty()
            && self.adjust_holdings.is_empty()
            && self.modify_purchases.is_empty()
    }

    /// Drop degenerate/hallucinated records the model sometimes emits: an
    /// `UNKNOWN`/empty or non-ticker symbol, a non-positive amount on an added
    /// purchase, or a non-positive/unknown USD cost. A `$0` cost is never a
    /// real purchase (it would imply infinite P&L) — the model invents it when
    /// it cannot convert a fiat amount, so we reject it instead of poisoning
    /// the portfolio. Returns how many records were removed.
    pub fn sanitize(&mut self) -> usize {
        let before = self.change_count();
        self.add_purchases.retain(|p| {
            is_valid_symbol(&p.symbol)
                && p.amount.is_finite()
                && p.amount > 0.0
                && p.cost_usd.is_finite()
                && p.cost_usd > 0.0
        });
        self.adjust_holdings.retain(|a| {
            is_valid_symbol(&a.symbol) && a.new_amount.is_finite() && a.new_amount >= 0.0
        });
        self.modify_purchases.retain(|m| {
            m.new_amount
                .map(|a| a.is_finite() && a > 0.0)
                .unwrap_or(true)
                && m
                    .new_cost_usd
                    .map(|c| c.is_finite() && c > 0.0)
                    .unwrap_or(true)
        });
        before - self.change_count()
    }

    /// Total number of changes in this patch.
    pub fn change_count(&self) -> usize {
        self.add_purchases.len()
            + self.remove_purchase_ids.len()
            + self.adjust_holdings.len()
            + self.modify_purchases.len()
    }
}

/// A pending patch waiting for user approval.
#[derive(Debug, Clone)]
pub struct PendingPatch {
    pub user_id: u64,
    pub patch: PortfolioPatch,
    pub expires_at: std::time::Instant,
}

impl PendingPatch {
    pub fn new(user_id: u64, patch: PortfolioPatch) -> Self {
        Self {
            user_id,
            patch,
            expires_at: std::time::Instant::now() + std::time::Duration::from_secs(600),
        }
    }

    pub fn is_expired(&self) -> bool {
        std::time::Instant::now() > self.expires_at
    }
}

/// A plausible ticker: non-empty ASCII alphanumerics containing at least one
/// letter and not the placeholder `UNKNOWN` the model emits for unparseable
/// assets.
fn is_valid_symbol(s: &str) -> bool {
    let s = s.trim();
    !s.is_empty()
        && !s.eq_ignore_ascii_case("UNKNOWN")
        && s.chars().all(|c| c.is_ascii_alphanumeric())
        && s.chars().any(|c| c.is_ascii_alphabetic())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn new_purchase(symbol: &str, amount: f64) -> NewPurchase {
        NewPurchase {
            symbol: symbol.to_string(),
            amount,
            cost_usd: 1000.0,
            wallet_name: None,
            source: None,
            notes: None,
            date: None,
        }
    }

    #[test]
    fn sanitize_drops_unknown_and_zero_amount() {
        let mut patch = PortfolioPatch {
            add_purchases: vec![
                new_purchase("UNKNOWN", 0.0),
                new_purchase("BTC", 0.0),
                new_purchase("ETH", 0.5),
            ],
            ..Default::default()
        };
        let dropped = patch.sanitize();
        assert_eq!(dropped, 2);
        assert_eq!(patch.add_purchases.len(), 1);
        assert_eq!(patch.add_purchases[0].symbol, "ETH");
    }

    #[test]
    fn sanitize_drops_zero_or_unknown_cost() {
        let mut patch = PortfolioPatch {
            add_purchases: vec![
                // The exact Nov-2026 bug: known amount, cost "unknown" -> 0.
                NewPurchase {
                    cost_usd: 0.0,
                    ..new_purchase("ETH", 0.39912391)
                },
                NewPurchase {
                    cost_usd: f64::NAN,
                    ..new_purchase("SOL", 1.0)
                },
                NewPurchase {
                    cost_usd: 666.67,
                    ..new_purchase("ETH", 0.39912391)
                },
            ],
            ..Default::default()
        };
        let dropped = patch.sanitize();
        assert_eq!(dropped, 2);
        assert_eq!(patch.add_purchases.len(), 1);
        assert!((patch.add_purchases[0].cost_usd - 666.67).abs() < 1e-9);
    }

    #[test]
    fn sanitize_drops_modify_with_zero_cost() {
        let mut patch = PortfolioPatch {
            modify_purchases: vec![PurchaseModify {
                purchase_id: 1,
                new_amount: None,
                new_cost_usd: Some(0.0),
                new_source: None,
                new_notes: None,
                new_date: None,
            }],
            ..Default::default()
        };
        assert_eq!(patch.sanitize(), 1);
        assert!(patch.modify_purchases.is_empty());
    }

    #[test]
    fn sanitize_keeps_zero_adjust_but_drops_unknown_symbol() {
        let mut patch = PortfolioPatch {
            adjust_holdings: vec![
                HoldingAdjust {
                    symbol: "UNKNOWN".into(),
                    wallet_name: None,
                    new_amount: 1.0,
                },
                HoldingAdjust {
                    symbol: "BTC".into(),
                    wallet_name: None,
                    new_amount: 0.0,
                },
            ],
            ..Default::default()
        };
        assert_eq!(patch.sanitize(), 1);
        assert_eq!(patch.adjust_holdings.len(), 1);
        assert_eq!(patch.adjust_holdings[0].symbol, "BTC");
    }

    #[test]
    fn valid_symbols_are_recognised() {
        assert!(is_valid_symbol("BTC"));
        assert!(is_valid_symbol("1INCH"));
        assert!(!is_valid_symbol("UNKNOWN"));
        assert!(!is_valid_symbol("unknown"));
        assert!(!is_valid_symbol("60000"));
        assert!(!is_valid_symbol(""));
        assert!(!is_valid_symbol("BTC USD"));
    }
}
